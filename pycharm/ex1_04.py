# 예제 1-4. 딕셔너리로 만든 신호 규칙
# 1-1 드론 연결과 신호 출력

from drone_sim import *

신호표 = {
    "대기": {"색": (0, 0, 255),   "음": Note.C5, "횟수": 1},
    "정상": {"색": (0, 255, 0),   "음": Note.E5, "횟수": 1},
    "주의": {"색": (255, 255, 0), "음": Note.E4, "횟수": 2},
    "위험": {"색": (255, 0, 0),   "음": Note.C4, "횟수": 3},
}

drone = Drone()
drone.pair()

상태 = "주의"                       # 이 값만 바꾸어 보세요
규칙 = 신호표[상태]
r, g, b = 규칙["색"]
drone.set_drone_LED(r, g, b, 100)
for i in range(규칙["횟수"]):
    drone.drone_buzzer(규칙["음"], 200)

print(f"'{상태}' 신호를 보냈습니다.")
drone.close()


