# 예제 2-11. 비행 임무 클래스
# 2-3 클래스·객체와 상속

class 비행임무:
    def __init__(self, 이름, 구간목록, 배터리기준=50):
        self.이름 = 이름                  # 속성
        self.구간목록 = 구간목록
        self.배터리기준 = 배터리기준
        self.완료 = False

    def 총거리(self):                     # 메서드
        return sum(self.구간목록)

    def 수행가능(self, 배터리):
        return 배터리 >= self.배터리기준

    def 요약(self):
        표시 = "완료" if self.완료 else "대기"
        return f"[{self.이름}] 구간 {len(self.구간목록)}개, 총 {self.총거리()} cm, {표시}"

임무A = 비행임무("운동장 순찰", [200, 150, 200, 150])
임무B = 비행임무("교실 왕복", [100, 100], 배터리기준=30)

임무A.완료 = True
print(임무A.요약())
print(임무B.요약())
print("배터리 40 %일 때 수행 가능?", 임무A.수행가능(40), 임무B.수행가능(40))


