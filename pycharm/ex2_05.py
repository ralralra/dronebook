# 예제 2-5. 임무 검사에서 오류 일으키기
# 2-1 함수와 예외 처리

class 임무오류(Exception):
    """임무 내용이 올바르지 않을 때"""

허용동작 = {"전진", "왼쪽회전", "신호"}

def 임무확인(임무):
    if len(임무) == 0:
        raise 임무오류("단계가 하나도 없습니다.")
    for 번호, 단계 in enumerate(임무, 1):
        if 단계.get("동작") not in 허용동작:
            raise 임무오류(f"{번호}단계: 모르는 동작 '{단계.get('동작')}'")
        if 단계["동작"] == "전진" and not (1 <= 단계["값"] <= 300):
            raise 임무오류(f"{번호}단계: 전진 거리 {단계['값']} cm 가 범위를 벗어남")

시험용 = {
    "정상": [{"동작": "전진", "값": 100}, {"동작": "왼쪽회전", "값": 90}],
    "빈 임무": [],
    "거리 초과": [{"동작": "전진", "값": 700}],
}
for 이름, 임무 in 시험용.items():
    try:
        임무확인(임무)
        print(f"{이름:6s} → 이상 없음")
    except 임무오류 as e:
        print(f"{이름:6s} → {e}")


# ----- 실행 결과 (가상 드론) -----
# 정상     → 이상 없음
# 빈 임무   → 단계가 하나도 없습니다.
# 거리 초과  → 1단계: 전진 거리 700 cm 가 범위를 벗어남
