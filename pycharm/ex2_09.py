# 예제 2-9. 일정한 간격으로 되풀이하기
# 2-2 표준 라이브러리 활용

import time

시작 = time.time()
for i in range(5):
    지난시간 = time.time() - 시작
    print(f"{i}번째 읽기 - 시작 후 {지난시간:.2f}초")
    time.sleep(0.2)                   # 0.2초 쉬다
print(f"전체 {time.time() - 시작:.1f}초 걸림")


