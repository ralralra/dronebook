# 1번째 읽기 - 시작 후 0.20초
# 2번째 읽기 - 시작 후 0.40초
# 3번째 읽기 - 시작 후 0.60초
# 4번째 읽기 - 시작 후 0.80초
# 전체 1.0초 걸림
