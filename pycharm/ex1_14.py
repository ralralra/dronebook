# 예제 1-14. 딕셔너리로 임무 표현하기
# 1-4 조건·반복·자료구조를 활용한 비행

from drone_sim import *

임무 = [
    {"동작": "전진", "값": 100},
    {"동작": "왼쪽회전", "값": 90},
    {"동작": "전진", "값": 80},
    {"동작": "신호", "값": (255, 255, 0)},
    {"동작": "왼쪽회전", "값": 90},
    {"동작": "전진", "값": 100},
]

drone = Drone()
drone.pair()
drone.takeoff()

for 단계 in 임무:
    동작, 값 = 단계["동작"], 단계["값"]
    if 동작 == "전진":
        drone.move_forward(값)
    elif 동작 == "왼쪽회전":
        drone.turn_left(값)
    elif 동작 == "신호":
        r, g, b = 값
        drone.set_drone_LED(r, g, b, 100)
    else:
        print("모르는 동작:", 동작)

drone.land()
print(f"최종 위치: x={drone.get_pos_x():.0f}, y={drone.get_pos_y():.0f}")
drone.close()


