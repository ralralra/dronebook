# 예제 2-19. 여러 기록을 하나로 모으기
# 2-5 비행 기록 관리 및 분석
# 필요한 라이브러리: pandas
# 먼저 ex2_18.py 를 실행해야 합니다. 그 예제가 만든 파일을 이 예제가 읽습니다.

import pandas as pd

모음 = []
for 바람 in [0, 2, 4]:
    df = pd.read_csv(f"flight_wind{바람}.csv")
    df["바람"] = 바람                    # 어느 비행인지 표시
    모음.append(df)
전체 = pd.concat(모음, ignore_index=True)
전체["y"] = 전체["y"] + 0.0          # -0.0 을 0.0 으로 정리
print("전체 기록:", 전체.shape)

마지막 = 전체.groupby("바람").tail(1).set_index("바람")
print(마지막[["x", "y", "배터리"]])


