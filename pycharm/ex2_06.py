# 예제 2-6. 목표 지점까지의 거리와 각도
# 2-2 표준 라이브러리 활용

import math

def 거리와각도(현재, 목표):
    """현재 위치에서 목표까지의 거리(cm)와 돌아야 할 각도(도, 왼쪽 +)를 돌려준다."""
    dx = 목표[0] - 현재[0]
    dy = 목표[1] - 현재[1]
    거리 = math.dist(현재, 목표)
    각도 = math.degrees(math.atan2(dy, dx))
    return round(거리, 1), round(각도, 1)

for 목표 in [(100, 0), (0, 100), (100, 100), (0, -100), (-100, 0)]:
    거리, 각도 = 거리와각도((0, 0), 목표)
    print(f"{str(목표):>11} → 거리 {거리:6.1f} cm, 각도 {각도:6.1f} 도")


