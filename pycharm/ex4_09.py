# 예제 4-9. 빨강의 색상값 들여다보기
# 4-3 센서 데이터 기반 분류 모델 학습 및 평가
# 필요한 라이브러리: pandas
# 먼저 ex4_08.py 를 실행해야 합니다. 그 예제가 만든 파일을 이 예제가 읽습니다.

import pandas as pd

색데이터 = pd.read_csv("color_data.csv")
빨강 = 색데이터[색데이터["색"] == "red"]["H"]
print("red 의 H 값 범위:", 빨강.min(), "~", 빨강.max())
print("30 미만:", (빨강 < 30).sum(), "개 / 330 초과:", (빨강 > 330).sum(), "개 / 그 사이:", ((빨강 >= 30) & (빨강 <= 330)).sum(), "개")


# ----- 실행 결과 (가상 드론) -----
# red 의 H 값 범위: 0.0 ~ 359.0
