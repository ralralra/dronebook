# 예제 1-5. 자동 점검과 눈으로 하는 점검
# 1-2 상태 점검과 기본 비행 및 비상 대응

from drone_sim import *

drone = Drone()
drone.pair()

# (1) 프로그램이 확인하는 항목
자동점검 = {
    "배터리 50% 이상": drone.get_battery() >= 50,
    "땅에 있음": drone.get_flight_state().name == "Ready",
    "높이 5cm 미만": drone.get_height() < 5,
}

# (2) 사람이 눈으로 확인하는 항목
눈점검 = ["프로펠러 파손 없음", "반경 2 m 안에 사람 없음", "보호 안경 착용"]

print("[자동 점검]")
for 항목, 결과 in 자동점검.items():
    표시 = "통과" if 결과 else "실패"
    print(f"  {항목:12s} {표시}")

print("[눈으로 확인할 항목]")
for 항목 in 눈점검:
    print(f"  [ ] {항목}")

print("자동 점검 모두 통과:", all(자동점검.values()))
drone.close()


