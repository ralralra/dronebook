# 예제 1-16. 임무가 올바른지 먼저 검사하기
# 1-4 조건·반복·자료구조를 활용한 비행

허용동작 = {"전진", "왼쪽회전", "신호"}

임무 = [
    {"동작": "전진", "값": 100},
    {"동작": "전진", "값": 900},        # 교실보다 길다
    {"동작": "공중제비", "값": 1},       # 모르는 동작
]

문제 = []
for 번호, 단계 in enumerate(임무, 1):
    동작, 값 = 단계.get("동작"), 단계.get("값")
    if 동작 not in 허용동작:
        문제.append(f"{번호}단계: 모르는 동작 '{동작}'")
    elif 동작 == "전진" and not (1 <= 값 <= 300):
        문제.append(f"{번호}단계: 전진 거리 {값} cm 가 범위(1~300)를 벗어남")

if 문제:
    print("임무를 실행할 수 없습니다.")
    for m in 문제:
        print("  -", m)
else:
    print("이상 없음. 실행합니다.")


