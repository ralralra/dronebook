# 예제 2-13. 임무마다 다른 준비 과정
# 2-3 클래스·객체와 상속

class 비행임무:
    def __init__(self, 이름):
        self.이름 = 이름
    def 준비(self):
        print(f"[{self.이름}] 기본 점검을 합니다.")

class 촬영임무(비행임무):
    def 준비(self):
        super().준비()
        print(f"[{self.이름}]   + 카메라 렌즈를 닦습니다.")

class 배송임무(비행임무):
    def __init__(self, 이름, 화물무게):
        super().__init__(이름)
        self.화물무게 = 화물무게
    def 준비(self):
        super().준비()
        if self.화물무게 > 30:
            print(f"[{self.이름}]   + 화물 {self.화물무게} g 은 너무 무거워 임무를 취소합니다.")
        else:
            print(f"[{self.이름}]   + 화물 {self.화물무게} g 을 단단히 고정합니다.")

오늘임무 = [비행임무("순찰"), 촬영임무("행사 촬영"), 배송임무("쪽지 배달", 12), 배송임무("책 배달", 300)]
for 임무 in 오늘임무:
    임무.준비()


