# [행사 촬영] 기본 점검을 합니다.
# [행사 촬영]   + 카메라 렌즈를 닦습니다.
# [쪽지 배달] 기본 점검을 합니다.
# [쪽지 배달]   + 화물 12 g 을 단단히 고정합니다.
# [책 배달] 기본 점검을 합니다.
# [책 배달]   + 화물 300 g 은 너무 무거워 임무를 취소합니다.
