# 예제 4-5. 규칙으로 판단하기
# 4-2 규칙 기반 제어와 기계학습의 비교

def 규칙판단(거리, 기울기, 배터리):
    """사람이 정한 기준으로 비행 계속 여부를 판단한다. 1 = 계속, 0 = 중단"""
    if 거리 < 50:
        return 0
    if 기울기 > 8:
        return 0
    if 배터리 < 30:
        return 0
    return 1

시험 = [(120, 2.0, 80), (40, 1.5, 90), (100, 9.5, 70), (130, 3.0, 25), (52, 7.6, 31)]
for 거리, 기울기, 배터리 in 시험:
    결과 = "계속" if 규칙판단(거리, 기울기, 배터리) else "중단"
    print(f"거리 {거리:>4} 기울기 {기울기:>4} 배터리 {배터리:>3} → {결과}")


# ----- 실행 결과 (가상 드론) -----
# 거리  120 기울기  2.0 배터리  80 → 계속
# 거리   40 기울기  1.5 배터리  90 → 중단
# 거리  100 기울기  9.5 배터리  70 → 중단
# 거리  130 기울기  3.0 배터리  25 → 중단
# 거리   52 기울기  7.6 배터리  31 → 계속
